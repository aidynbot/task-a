def build_user_prompt(document_text: str, error_feedback: str | None = None) -> str:
    """Формирует пользовательский промпт с текстом документа и опциональной ошибкой валидации для ретрая."""
    prompt = f"Извлеки данные из следующего документа строго по схеме:\n\n--- НАЧАЛО ДОКУМЕНТА ---\n{document_text}\n--- КОНЕЦ ДОКУМЕНТА ---"

    if error_feedback:
        prompt += (
            "\n\nВНИМАНИЕ! Предыдущий ответ не прошёл программную валидацию схемы:\n"
            f"{error_feedback}\n"
            "Исправь указанную ошибку формата или типа данных, строго соблюдая правила из системной инструкции."
        )

    return prompt